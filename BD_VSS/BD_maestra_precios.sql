-- Crear tabla usuario
CREATE TABLE usuario (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100),
  correo VARCHAR(100),
  rol VARCHAR(50),
  activo BOOLEAN,
  fecha_creacion TIMESTAMP
);

-- Crear tabla tipo_cambio
CREATE TABLE tipo_cambio (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha DATE UNIQUE,
  valor DECIMAL(10,4),
  fuente VARCHAR(100),
  usuario_registro_id BIGINT,
  fecha_registro TIMESTAMP
);

-- Crear tabla cliente
CREATE TABLE cliente (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_barco VARCHAR(100) UNIQUE,
  imo_numero VARCHAR(20),
  empresa_operadora VARCHAR(100),
  correo_contacto VARCHAR(100),
  puerto_base VARCHAR(100),
  pais_origen VARCHAR(50),
  tipo_cliente VARCHAR(50),
  capitan VARCHAR(100),
  cocinero_jefe VARCHAR(100),
  observaciones TEXT,
  activo BOOLEAN,
  fecha_creacion TIMESTAMP
);

-- Crear tabla cotizacion
CREATE TABLE cotizacion (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id BIGINT,
  fecha_solicitud DATE,
  puerto_destino VARCHAR(100),
  archivo_origen VARCHAR(100),
  observaciones TEXT,
  usuario_importador_id BIGINT,
  fecha_importacion TIMESTAMP
);

-- Crear tabla familia_producto
CREATE TABLE familia_producto (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) UNIQUE,
  descripcion TEXT
);

-- Crear tabla producto
CREATE TABLE producto (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  familia VARCHAR(100),
  descripcion_en TEXT,
  descripcion_es TEXT,
  unidad_medida VARCHAR(20),
  valor_pesos DECIMAL(12,2),
  precio_costo_neto DECIMAL(12,2),
  porcentaje_utilidad DECIMAL(5,2),
  precio_venta_neto DECIMAL(12,2),
  tipo_cambio_usado DECIMAL(10,4),
  fecha_actualizacion TIMESTAMP,
  usuario_editor_id BIGINT
);

-- Crear tabla item_cotizacion
CREATE TABLE item_cotizacion (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cotizacion_id BIGINT,
  producto_id BIGINT,
  descripcion TEXT,
  unidad_medida VARCHAR(20),
  valor_pesos DECIMAL(12,2),
  tipo_cambio_usado DECIMAL(10,4),
  precio_costo_neto DECIMAL(12,2),
  porcentaje_utilidad DECIMAL(5,2),
  precio_venta_neto DECIMAL(12,2),
  cantidad INT,
  total_neto DECIMAL(12,2),
  comentarios TEXT
);

-- Crear tabla log_importacion
CREATE TABLE log_importacion (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cotizacion_id BIGINT,
  usuario_id BIGINT,
  fecha TIMESTAMP,
  total_items INT,
  items_vinculados INT,
  items_no_encontrados INT,
  errores_detectados TEXT,
  resumen TEXT
);

-- Relaciones (claves foráneas)
ALTER TABLE tipo_cambio ADD FOREIGN KEY (usuario_registro_id) REFERENCES usuario (id);
ALTER TABLE cotizacion ADD FOREIGN KEY (cliente_id) REFERENCES cliente (id);
ALTER TABLE cotizacion ADD FOREIGN KEY (usuario_importador_id) REFERENCES usuario (id);
ALTER TABLE producto ADD FOREIGN KEY (usuario_editor_id) REFERENCES usuario (id);
ALTER TABLE producto ADD FOREIGN KEY (familia) REFERENCES familia_producto (nombre);
ALTER TABLE item_cotizacion ADD FOREIGN KEY (cotizacion_id) REFERENCES cotizacion (id);
ALTER TABLE item_cotizacion ADD FOREIGN KEY (producto_id) REFERENCES producto (id);
ALTER TABLE log_importacion ADD FOREIGN KEY (cotizacion_id) REFERENCES cotizacion (id);
ALTER TABLE log_importacion ADD FOREIGN KEY (usuario_id) REFERENCES usuario (id);
